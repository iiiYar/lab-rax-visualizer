/** Part name for a table cell or card; "Height rail 5U" keeps its number. */
function partText(en: string, ar: boolean): string {
  if (!ar) return escapeHtml(en)
  const h = /^Height rail (\d+)U$/.exec(en)
  if (h) return `قائم ارتفاع ${h[1]}U`
  const s = /^Side panel (\d+)U$/.exec(en)
  if (s) return `لوح جانبي ${s[1]}U`
  return escapeHtml(PART_AR[en] ?? en)
}

const jointAr = (s: string): string => {
  if (s === 'One joint') return 'وصلة واحدة'
  const n = Number(s.split(' ')[0])
  return n === 2 ? 'وصلتان' : `${n} وصلات`
}

const timesAr = (n: number): string => (n === 1 ? 'مرة واحدة' : n === 2 ? 'مرتين' : `${n} مرات`)

