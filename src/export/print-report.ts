interface Piece {
  text: string
  html?: string
}

/** Wrap Latin file names and URLs so they keep their order inside Arabic text. */
function linkLatin(escaped: string): string {
  return escaped.replace(/(https?:\/\/[^\s<]+|[\w/.-]*\.(?:stl|3mf|py)\b)/g, '<bdi dir="ltr">$1</bdi>')
}

/**
 * Arabic for free text. Matched fragments become Arabic HTML; whatever no rule
 * matched is kept in English (escaped), so unknown text is never dropped.
 */
function arText(en: string): string {
  let pieces: Piece[] = [{ text: en }]
  for (const rule of RULES) {
    const next: Piece[] = []
    for (const p of pieces) {
      if (p.html !== undefined) {
        next.push(p)
        continue
      }
      const re = new RegExp(rule.re.source, 'g')
      let last = 0
      let m: RegExpExecArray | null
      while ((m = re.exec(p.text)) !== null) {
        if (m.index > last) next.push({ text: p.text.slice(last, m.index) })
        next.push({ text: '', html: rule.to(m) })
        last = m.index + m[0].length
        if (m[0].length === 0) re.lastIndex++
      }
      if (last < p.text.length) next.push({ text: p.text.slice(last) })
    }
    pieces = next
  }
  return pieces.map((p) => (p.html !== undefined ? p.html : linkLatin(escapeHtml(p.text)))).join('')
}

