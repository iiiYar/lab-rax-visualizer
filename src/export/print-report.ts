/** Ticks persist per build (slug) and row number; a blocked localStorage is harmless. */
function script(slug: string): string {
  return `(function () {
  var slug = ${JSON.stringify(slug)};
  function key(no) { return 'lab-rax-print:' + slug + ':' + no; }
  function paint(box) {
    var row = box.closest ? box.closest('.row') : null;
    if (row) row.classList.toggle('done', box.checked);
  }
  var boxes = document.querySelectorAll('input[type=checkbox][data-no]');
  for (var i = 0; i < boxes.length; i++) {
    (function (box) {
      try {
        if (window.localStorage.getItem(key(box.getAttribute('data-no'))) === '1') box.checked = true;
      } catch (e) { /* storage blocked: the list still works, ticks just do not persist */ }
      paint(box);
      box.addEventListener('change', function () {
        paint(box);
        try { window.localStorage.setItem(key(box.getAttribute('data-no')), box.checked ? '1' : '0'); } catch (e) { /* see above */ }
      });
    })(boxes[i]);
  }
})();`
}

/**
 * A self-contained sheet: open it in any browser, tick parts off as they come
 * off the bed, print it if you prefer paper. The tick boxes are real inputs.
 * Only print/review rows go in the queue; bought, cut and download-only rows
 * get their own tables below, so the queue stays a list you can tick through.
 */
export function printReportHtml(
  rows: ManifestRow[],
  state: BuildState,
  lang: ReportLang,
  generatedAt = new Date(),
): string {
  const ar = lang === 'ar'
  const T = ar ? AR : EN
  const tr = (en: string): string => (ar ? arText(en) : escapeHtml(en))
  const totals = manifestTotals(rows)
  const queue = rows.filter((r) => r.status === 'print' || r.status === 'review')
  const missing = rows.filter((r) => r.status === 'download')
  const excluded = rows.filter((r) => r.status === 'source-only')
  const over = oversizeRows(rows)
  const date = generatedAt.toISOString().slice(0, 10)
  const slug = buildSlug(state.rackU, state.segments, state.joinerModel)
  const seg = segmentLabel(state.segments)
  const joints = Math.max(0, state.segments.length - 1)
  const joinerName = state.joinerModel === 'long' ? T.joinerLong : T.joinerShort

  // Frame hardware has its own table; drop it from "This build" so it is not listed twice.
  const hardware = frameHardware(state.segments, state.joinerModel)
  const buildRows = buildRequirements(state).filter((r) => !hardware.some((h) => h.item === r.item))

  const header = `<header class="band">
    <div>
      <h1>Lab Rax — ${state.rackU}U · ${escapeHtml(seg)}</h1>
      <p class="build">${T.posts} <bdi dir="ltr">${escapeHtml(seg)}</bdi> · ${joints} ${joints === 1 ? T.joint : T.joints} · ${T.joiners}: ${escapeHtml(joinerName)}</p>
    </div>
    <div class="date" dir="ltr">${date}</div>
  </header>
  <p class="hint">${T.hint}</p>`

  const card = (cls: string, n: number, label: string) =>
    `<div class="card${cls ? ` ${cls}` : ''}"><b>${n}</b><span>${escapeHtml(label)}</span></div>`
  const cards = `<section class="cards">
  ${card('hero', totals.pieces, T.cardPieces)}
  ${card('', totals.files, T.cardFiles)}
  ${card('', totals.byGroup.frame, T.cardFrame)}
  ${card('', totals.byGroup.shelves, T.cardShelves)}
  ${card('', totals.byGroup.accessories, T.cardAccessories)}
  ${totals.review > 0 ? card('review', totals.review, T.cardReview) : ''}
  ${totals.missing > 0 ? card('dl', totals.missing, T.cardDownload) : ''}
</section>`

  const bedItems = over
    .map((r) =>
      ar
        ? `${partText(r.part, true)} بمقاس <bdi dir="ltr">${escapeHtml(r.size)} ${T.mm}</bdi>`
        : `${escapeHtml(r.part)} is <bdi dir="ltr">${escapeHtml(r.size)} ${T.mm}</bdi>`,
    )
    .join(ar ? ' · ' : ' · ')
  const warnings = [
    state.rackU > DESIGN_LIMIT_U ? `<div class="warnbox"><b>${T.designLimit}</b>${tr(DESIGN_LIMIT_NOTE)}</div>` : '',
    over.length > 0 ? `<div class="warnbox"><b>${T.bedCheck}</b>${bedItems} ${T.bedWide}</div>` : '',
  ].join('\n')

  const rowHtml = (r: ManifestRow): string => {
    const n = r.no ?? 0
    const cls = STATUS_CLASS[r.status]
    const plain = ar ? partText(r.part, true) : escapeHtml(r.part)
    return `      <li class="row ${cls}">
        <div class="badge">${n}</div>
        <label class="tick"><input type="checkbox" data-no="${n}" aria-label="${escapeHtml(T.printedAria)}: ${escapeHtml(r.part)}"></label>
        <div class="body">
          <div class="head"><span class="part">${plain}</span><span class="unit" dir="ltr">${escapeHtml(r.unit)}</span></div>
          <div class="line"><code class="file" dir="ltr">${escapeHtml(r.file) || '—'}</code><span class="size">${r.size ? `<bdi dir="ltr">${escapeHtml(r.size)}</bdi> ${T.mm}` : '—'}</span></div>
          <div class="src">${sourceCell(r.source, ar)}</div>
          ${r.note ? `<p class="note">${tr(r.note)}</p>` : ''}
        </div>
        <div class="qty" dir="ltr">×${r.qty}</div>
        <div class="status"><span class="pill ${cls}">${T[STATUS_KEY[r.status]]}</span></div>
      </li>`
  }

  const queueGroups = GROUP_ORDER.filter((g) => queue.some((r) => r.group === g))
    .map((g) => {
      const list = queue.filter((r) => r.group === g)
      const pieces = list.reduce((n, r) => n + r.qty, 0)
      const files = list.length
      return `  <div class="group">
    <header class="group-head"><h3>${T[GROUP_KEY[g]]}</h3><span class="count">${pieces} ${T.pcs} · ${files} ${files === 1 ? T.file : T.files}</span></header>
    <ul class="rows">
${list.map(rowHtml).join('\n')}
    </ul>
  </div>`
    })
    .join('\n')

  const queueSection = `<section class="queue">
  <h2>${T.queue} <span class="muted">· ${totals.pieces} ${T.pcs} · ${totals.files} ${totals.files === 1 ? T.file : T.files}</span></h2>
${queueGroups}
</section>`

  const buildSection = `<div class="pair">
  <section class="panel">
    <h2>${T.build} <span class="muted">· ${T.posts} <bdi dir="ltr">${escapeHtml(seg)}</bdi></span></h2>
    <table><tbody>
${buildRows.map((r) => `      <tr><th scope="row">${tr(r.item)}</th><td>${tr(r.value)}</td></tr>`).join('\n')}
    </tbody></table>
  </section>
  <section class="panel">
    <h2>${T.hardwareBuy} <span class="muted">· ${T.notPrinted}</span></h2>
    <table><thead><tr><th>${T.item}</th><th>${T.quantity}</th></tr></thead><tbody>
${hardware.map((h) => `      <tr><th scope="row">${tr(h.item)}</th><td>${tr(h.qty)}</td></tr>`).join('\n')}
    </tbody></table>
  </section>
</div>`

  const missingSection =
    missing.length > 0
      ? `<section class="missing">
  <h2>${T.missingHead} <span class="muted">· ${missing.reduce((n, r) => n + r.qty, 0)} ${T.pcs}</span></h2>
  <div class="panel"><table>
    <thead><tr><th>${T.colUnit}</th><th>${T.colPart}</th><th>${T.colQty}</th><th>${T.colSource}</th><th>${T.colWhyMissing}</th></tr></thead>
    <tbody>
${missing
  .map(
    (r) => `      <tr>
        <td>${escapeHtml(r.unit)}</td>
        <td>${partText(r.part, ar)}</td>
        <td class="qty-cell">${r.qty}</td>
        <td>${sourceCell(r.source, ar)}</td>
        <td class="muted">${r.note ? tr(r.note) : '—'}</td>
      </tr>`,
  )
  .join('\n')}
    </tbody>
  </table></div>
</section>`
      : ''

  const excludedSection =
    excluded.length > 0
      ? `<section class="excluded">
  <h2>${T.excludedHead} <span class="muted">· ${excluded.length} ${ar ? 'صفوف' : 'rows'}</span></h2>
  <div class="panel"><table>
    <thead><tr><th>${T.colUnit}</th><th>${T.colPart}</th><th>${T.colFile}</th><th>${T.colQty}</th><th>${T.colWhyExcluded}</th></tr></thead>
    <tbody>
${excluded
  .map(
    (r) => `      <tr>
        <td>${escapeHtml(r.unit)}</td>
        <td>${partText(r.part, ar)}</td>
        <td><code class="file" dir="ltr">${escapeHtml(r.file)}</code></td>
        <td class="qty-cell">${r.qty}</td>
        <td class="muted">${r.note ? tr(r.note) : '—'}</td>
      </tr>`,
  )
  .join('\n')}
    </tbody>
  </table></div>
</section>`
      : ''

  // One row per distinct source, in the order each first appears on the sheet.
  const bySource = new Map<string, { s: PartSource; parts: Set<string> }>()
  for (const r of rows) {
    const key = r.source.url ?? r.source.label
    const hit = bySource.get(key)
    if (hit) hit.parts.add(r.part)
    else bySource.set(key, { s: r.source, parts: new Set([r.part]) })
  }
  const entries = Array.from(bySource.values())
  const mwCount = entries.filter((v) => v.s.kind === 'makerworld').length
  const supCount = entries.filter((v) => v.s.kind === 'supplied').length
  const unrecCount = entries.filter((v) => v.s.kind === 'unrecorded').length
  const countText = ar
    ? [
        `${mwCount} ${mwCount === 1 ? 'نموذج MakerWorld' : 'نماذج MakerWorld'}`,
        ...(supCount > 0 ? [`${supCount} ${supCount === 1 ? 'ملف مُرسل' : 'ملفات مُرسلة'}`] : []),
        ...(unrecCount > 0 ? [`${unrecCount} بمصدر غير مسجّل`] : []),
      ].join(' · ')
    : [
        `${mwCount} MakerWorld model${mwCount === 1 ? '' : 's'}`,
        ...(supCount > 0 ? [`${supCount} supplied file${supCount === 1 ? '' : 's'}`] : []),
        ...(unrecCount > 0 ? [`${unrecCount} with no recorded origin`] : []),
      ].join(' · ')

  const sourceRows = entries
    .map(({ s, parts }) => {
      const covers = Array.from(parts)
        .map((p) => partText(p, ar))
        .join(ar ? '، ' : ', ')
      if (s.kind === 'makerworld') {
        return `      <tr>
        <td>${escapeHtml(s.label)}</td>
        <td><bdi dir="ltr"><a href="${escapeHtml(s.url ?? '')}">${escapeHtml(s.url ?? '')}</a></bdi></td>
        <td>${covers}</td>
      </tr>`
      }
      if (s.kind === 'unrecorded') {
        return `      <tr>
        <td>${T.originNotRecorded}</td>
        <td>—</td>
        <td>${covers}${T.checkBeforePrint}</td>
      </tr>`
      }
      return `      <tr>
        <td>${tr(s.label)}</td>
        <td>—</td>
        <td>${covers}</td>
      </tr>`
    })
    .join('\n')

  const sourcesSection = `<section class="sources">
  <h2>${T.sourcesHead} <span class="muted">· ${countText}</span></h2>
  <div class="panel"><table>
    <thead><tr><th>${T.colSource}</th><th>${T.colLink}</th><th>${T.colCovers}</th></tr></thead>
    <tbody>
${sourceRows}
    </tbody>
  </table></div>
</section>`

  const footer = `<footer>
  <p><b>${T.footLead}</b> ${T.footBody}</p>
  <p>${T.generated}</p>
</footer>`

  return `<!doctype html>
<html lang="${lang}" dir="${ar ? 'rtl' : 'ltr'}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Lab Rax ${state.rackU}U — ${T.pageTitle}</title>
<style>${css(ar)}</style>
</head>
<body>
<div class="page">
${header}
${cards}
${warnings}
${queueSection}
${buildSection}
${missingSection}
${excludedSection}
${sourcesSection}
${footer}
</div>
<script>${script(slug)}</script>
</body>
</html>
`
}
